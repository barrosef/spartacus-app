/* ── Helpers ───────────────────────────────────────────────────────────── */

function formatPercent(ratio: number | null): string {
  if (ratio === null) return "—";
  return `${Math.round(ratio * 100)}%`;
}

function graduationLabel(g: { belt: string | null; degree: number | null }): string {
  if (!g.belt) return "Sem graduação";
  return g.degree ? `${g.belt} · grau ${g.degree}` : g.belt;
}

function trackWidths(counts: AttendanceCounts) {
  const denom = counts.confirmed + counts.absent + counts.justificationPending;
  if (denom === 0) return { ok: 0, rev: 0, miss: 0 };
  return {
    ok: (counts.confirmed / denom) * 100,
    rev: (counts.justificationPending / denom) * 100,
    miss: (counts.absent / denom) * 100,
  };
}

function buildQuery(params: Record<string, string | number | undefined | null>): string {
  const usp = new URLSearchParams();
  for (const [k, v] of Object.entries(params)) {
    if (v !== undefined && v !== null && v !== "") usp.set(k, String(v));
  }
  const qs = usp.toString();
  return qs ? `?${qs}` : "";
}

/* ── Component ─────────────────────────────────────────────────────────── */

interface FrequencyHistoryScreenProps {
  onBack: () => void;
}

export function FrequencyHistoryScreen({ onBack }: FrequencyHistoryScreenProps) {
  const { actingAs, actingAsName } = useProxy();
  const [screen, setScreen] = useState<Screen>("loading");
  const [data, setData] = useState<AttendanceHistory | null>(null);
  const [breakdownGroups, setBreakdownGroups] = useState<GraduationBreakdown[]>([]);
  const [breakdownLoading, setBreakdownLoading] = useState(false);
  const [refreshing, setRefreshing] = useState(false);

  const [modalityOptions, setModalityOptions] = useState<ModalityOption[]>([]);
  const [currentGraduation, setCurrentGraduation] = useState<Record<string, GraduationEntry>>({});

  const [selectedMonth, setSelectedMonth] = useState<string | null>(null);
  const [selectedModality, setSelectedModality] = useState<ModalityOption | null>(null);
  const [selectedGraduation, setSelectedGraduation] = useState<GraduationFilter | null>(null);
  const [filtersReady, setFiltersReady] = useState(false);
  const [filtersOpen, setFiltersOpen] = useState(false);
  const [justifyTarget, setJustifyTarget] = useState<AttendanceRecord | null>(null);

  const authHeaders = useCallback((): Record<string, string> => {
    const headers: Record<string, string> = {};
    if (actingAs) headers["X-Acting-As"] = actingAs;
    return headers;
  }, [actingAs]);

  /* Bootstrap: modalities + unfiltered history + profile graduation. */
  const bootstrap = useCallback(async () => {
    setScreen("loading");
    setFiltersReady(false);
    try {
      const headers = authHeaders();
      const projectId = getProjectId();
      const [history, modalitiesRes, profile] = await Promise.all([
        api.get<AttendanceHistory>("/attendance/history", { headers }),
        api.get<{ modalities: ModalityOut[] }>(`/projects/${projectId}/modalities`),
        api.get<ProfileData>("/users/me/profile", { headers }),
      ]);

      setData(history);
      setCurrentGraduation(profile.graduation ?? {});

      const namesInRecords = new Set<string>();
      history.months.forEach((m) =>
        m.records.forEach((r) => { if (r.modalityName) namesInRecords.add(r.modalityName); }),
      );
      const options = modalitiesRes.modalities
        .filter((mod) => namesInRecords.has(mod.name))
        .map((mod) => ({ name: mod.name, slug: mod.slug }));
      setModalityOptions(options);

      const hasRecords = history.months.some((m) => m.records.length > 0);
      setScreen(hasRecords ? "ready" : "empty");

      // Default dos filtros: mês mais recente disponível (o backend já corta
      // pela data-base da turma), modalidade e graduação em "Todas" — é o
      // estado que o ícone de filtro considera "sem filtro aplicado".
      setSelectedMonth(history.months[0]?.month ?? null);
      setSelectedModality(null);
      setSelectedGraduation(null);
      setFiltersReady(true);
    } catch {
      setScreen("error");
    }
  }, [authHeaders]);

  useEffect(() => { bootstrap(); }, [bootstrap]);

  /* Scoped fetch: honours month + modality + graduação (the 3 chained filters). */
  useEffect(() => {
    if (!filtersReady) return;
    let cancelled = false;
    (async () => {
      setRefreshing(true);
      try {
        const qs = buildQuery({
          month: selectedMonth ?? undefined,
          modality: selectedModality?.slug,
          belt: selectedGraduation?.belt,
          degree: selectedGraduation ? selectedGraduation.degree ?? undefined : undefined,
        });
        const res = await api.get<AttendanceHistory>(`/attendance/history${qs}`, { headers: authHeaders() });
        if (!cancelled) setData(res);
      } catch {
        if (!cancelled) setScreen("error");
      } finally {
        if (!cancelled) setRefreshing(false);
      }
    })();
    return () => { cancelled = true; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [selectedMonth, selectedModality, selectedGraduation, filtersReady, actingAs]);

  /* Breakdown fetch: month + modality only (never belt/degree) — feeds both
   * the graduação chip options and the "Recorte por graduação" cards. */
  useEffect(() => {
    if (!filtersReady) return;
    if (!selectedModality) { setBreakdownGroups([]); return; }
    let cancelled = false;
    (async () => {
      setBreakdownLoading(true);
      try {
        const qs = buildQuery({ month: selectedMonth ?? undefined, modality: selectedModality.slug });
        const res = await api.get<AttendanceHistory>(`/attendance/history${qs}`, { headers: authHeaders() });
        if (!cancelled) setBreakdownGroups(res.byGraduation);
      } catch {
        if (!cancelled) setBreakdownGroups([]);
      } finally {
        if (!cancelled) setBreakdownLoading(false);
      }
    })();
    return () => { cancelled = true; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [selectedMonth, selectedModality, filtersReady, actingAs]);

  /* ── Justificar falta (Task B7) ── */
  if (justifyTarget) {
    return (
      <JustifyAbsenceScreen
        record={{
          id: justifyTarget.id,
          date: justifyTarget.date,
          modalityName: justifyTarget.modalityName,
        }}
        onClose={() => setJustifyTarget(null)}
        onJustified={() => {
          setJustifyTarget(null);
          bootstrap();
        }}
      />
    );
  }

  /* ── Loading ── */
  if (screen === "loading") {
    return (
      <SafeAreaView style={styles.safe} edges={["top"]}>
        <ScreenHeader onBack={onBack} subtitle={actingAsName ? `Frequência de ${actingAsName}` : undefined} />
        <View style={styles.center}>
          <ActivityIndicator size="large" color={colors.primary} />
        </View>
      </SafeAreaView>
    );
  }

  /* ── Error ── */
  if (screen === "error") {
    return (
      <SafeAreaView style={styles.safe} edges={["top"]}>
        <ScreenHeader onBack={onBack} />
        <View style={styles.center}>
          <View style={styles.emptyIcon}>
            <Feather name="alert-triangle" size={28} color={colors.error} />
          </View>
          <Text style={styles.emptyTitle}>Não foi possível carregar</Text>
          <Text style={styles.emptyMsg}>
            Verifique sua conexão e tente novamente.
          </Text>
          <View style={styles.retryWrap}>
            <Button label="Tentar novamente" onPress={bootstrap} />
          </View>
        </View>
      </SafeAreaView>
    );
  }

  /* ── Empty ── */
  if (screen === "empty" || !data) {
    return (
      <SafeAreaView style={styles.safe} edges={["top"]}>
        <ScreenHeader onBack={onBack} subtitle={actingAsName ? `Frequência de ${actingAsName}` : undefined} />
        <View style={styles.center}>
          <View style={styles.emptyIcon}>
            <Feather name="calendar" size={28} color={colors.mutedForeground} />
          </View>
          <Text style={styles.emptyTitle}>Nenhum registro</Text>
          <Text style={styles.emptyMsg}>
            Seus dados de frequência aparecerão aqui após o primeiro check-in.
          </Text>
        </View>
      </SafeAreaView>
    );
  }

  /* ── Ready ── */
  const monthOptions = data.months;
  const selectedMonthSummary = monthOptions.find((m) => m.month === selectedMonth) ?? monthOptions[0];
  const monthRecordsAll = selectedMonthSummary?.records ?? [];
  const monthRecords = selectedModality
    ? monthRecordsAll.filter((r) => r.modalityName === selectedModality.name)
    : monthRecordsAll;

  const widths = trackWidths(data.counts);

  // "Current" graduation group for the selected modality (highlighted, no
  // "Faixa anterior" tag); everything else in scope is archived.
  const currentEntry = selectedModality
    ? currentGraduation[normalizeModalityKey(selectedModality.name)]
    : undefined;
  const gradedGroups = breakdownGroups.filter((g) => g.key !== "no_graduation" && g.belt);
  const noGraduationGroup = breakdownGroups.find((g) => g.key === "no_graduation");
  let currentGroup = currentEntry
    ? gradedGroups.find((g) => g.belt === currentEntry.belt && g.degree === currentEntry.degree)
    : undefined;
  if (!currentGroup && gradedGroups.length === 1) currentGroup = gradedGroups[0];
  const archivedGroups = gradedGroups.filter((g) => g.key !== currentGroup?.key);

  // Ponto dourado no ícone: algum filtro fora do default (mês mais recente,
  // modalidade e graduação em "Todas").
  const filterActive =
    !!selectedModality ||
    !!selectedGraduation ||
    (!!selectedMonth && selectedMonth !== monthOptions[0]?.month);

  return (
    <SafeAreaView style={styles.safe} edges={["top"]}>
      <ScreenHeader
        onBack={onBack}
        subtitle={actingAsName ? `Frequência de ${actingAsName}` : undefined}
        onFilter={() => setFiltersOpen(true)}
        filterActive={filterActive}
      />
      <ScrollView
        contentContainerStyle={styles.scroll}
        showsVerticalScrollIndicator={false}
      >
        {/* KPIs */}
        <View style={styles.kpiRow}>
          <View style={[styles.kpi, styles.kpiHero]}>
            <Text style={styles.kpiValueHero}>{formatPercent(data.percent)}</Text>
            <Text style={styles.kpiLabel}>Frequência</Text>
          </View>
          <View style={styles.kpi}>
            <Text style={styles.kpiValue}>🔥{data.streakDays}</Text>
            <Text style={styles.kpiLabel}>Sequência</Text>
          </View>
          <View style={styles.kpi}>
            <Text style={styles.kpiValue}>{data.counts.confirmed}</Text>
            <Text style={styles.kpiLabel}>Presenças</Text>
          </View>
        </View>
        {refreshing && (
          <ActivityIndicator size="small" color={colors.primary} style={styles.refreshSpinner} />
        )}

        {/* Resumo do mês */}
        <Text style={styles.sectionTitle}>RESUMO DO MÊS</Text>
        <View style={styles.monthCard}>
          <View style={styles.monthTop}>
            <Text style={styles.monthLabel}>{selectedMonthSummary?.monthLabel ?? "—"}</Text>
            <Text style={styles.monthPercent}>{formatPercent(data.percent)}</Text>
          </View>
          <View style={styles.track}>
            {widths.ok > 0 && <View style={[styles.trackFill, { width: `${widths.ok}%`, backgroundColor: colors.success }]} />}
            {widths.rev > 0 && <View style={[styles.trackFill, { width: `${widths.rev}%`, backgroundColor: colors.warning }]} />}
            {widths.miss > 0 && <View style={[styles.trackFill, { width: `${widths.miss}%`, backgroundColor: colors.error }]} />}
          </View>
          <View style={styles.legend}>
            <LegendItem color={colors.success} text={`${data.counts.confirmed} confirmadas`} />
            <LegendItem color={colors.warning} text={`${data.counts.justificationPending} em análise`} />
            <LegendItem color={colors.error} text={`${data.counts.absent} faltas`} />
            <LegendItem color={colors.primary} text={`${data.counts.absentJustified} justificada${data.counts.absentJustified === 1 ? "" : "s"}`} />
          </View>
        </View>

        {/* Recorte por graduação */}
        <Text style={styles.sectionTitle}>RECORTE POR GRADUAÇÃO</Text>
        {!selectedModality ? (
          <Text style={styles.hint}>Selecione uma modalidade para ver o recorte por graduação.</Text>
        ) : breakdownLoading ? (
          <ActivityIndicator size="small" color={colors.primary} style={styles.refreshSpinner} />
        ) : gradedGroups.length === 0 && !noGraduationGroup ? (
          <Text style={styles.hint}>Sem registros nesta modalidade no período selecionado.</Text>
        ) : (
          <View style={{ gap: spacing.sm + 4 }}>
            {currentGroup && (
              <GraduationCard
                group={currentGroup}
                modalityName={selectedModality.name}
                archived={false}
              />
            )}
            {archivedGroups.map((g) => (
              <GraduationCard
                key={g.key}
                group={g}
                modalityName={selectedModality.name}
                archived
              />
            ))}
            {noGraduationGroup && (
              <GraduationCard group={noGraduationGroup} modalityName={selectedModality.name} archived />
            )}
          </View>
        )}

        {/* Presenças recentes */}
        <Text style={styles.sectionTitle}>PRESENÇAS RECENTES</Text>
        {monthRecords.length === 0 ? (
          <Text style={styles.hint}>Nenhum registro para este filtro.</Text>
        ) : (
          <View style={styles.recordList}>
            {monthRecords.map((r) => (
              <RecordRow
                key={r.id}
                record={r}
                canJustify={
                  r.status === "absent" &&
                  isRealRecordId(r.id) &&
                  withinJustifyPrazo(r.dateSort)
                }
                // Falta real fora do prazo: em vez de simplesmente não ter
                // botão (que lê como "a função não existe"), diz o motivo.
                prazoExpired={
                  r.status === "absent" &&
                  isRealRecordId(r.id) &&
                  !withinJustifyPrazo(r.dateSort)
                }
                onJustify={() => setJustifyTarget(r)}
              />
            ))}
          </View>
        )}
      </ScrollView>

      {/* Filtros — padrão do app: ícone no header, painel pela direita */}
      <FilterPanel
        visible={filtersOpen}
        onClose={() => setFiltersOpen(false)}
        title="Filtros"
      >
        <View style={styles.filterSection}>
          <Text style={styles.filterSectionTitle}>Período</Text>
          <SelectBox
            value={selectedMonth}
            placeholder="Selecione o mês"
            options={monthOptions.map((m) => ({
              value: m.month,
              label: m.monthLabel,
            }))}
            onChange={setSelectedMonth}
          />
        </View>

        {modalityOptions.length > 0 && (
          <View style={styles.filterSection}>
            <Text style={styles.filterSectionTitle}>Modalidade</Text>
            <View style={styles.chipsWrap}>
              <Chip
                label="Todas"
                active={!selectedModality}
                onPress={() => { setSelectedModality(null); setSelectedGraduation(null); }}
              />
              {modalityOptions.map((mod) => (
                <Chip
                  key={mod.slug}
                  label={mod.name}
                  active={selectedModality?.slug === mod.slug}
                  onPress={() => { setSelectedModality(mod); setSelectedGraduation(null); }}
                />
              ))}
            </View>
          </View>
        )}

        {selectedModality && gradedGroups.length > 0 && (
          <View style={styles.filterSection}>
            <Text style={styles.filterSectionTitle}>Graduação</Text>
            <View style={styles.chipsWrap}>
              <Chip label="Todas" active={!selectedGraduation} onPress={() => setSelectedGraduation(null)} />
              {gradedGroups.map((g) => (
                <Chip
                  key={g.key}
                  label={graduationLabel(g)}
                  active={selectedGraduation?.key === g.key}
                  onPress={() => setSelectedGraduation({ key: g.key, belt: g.belt!, degree: g.degree })}
                />
              ))}
            </View>
          </View>
        )}
      </FilterPanel>
    </SafeAreaView>
  );
}

