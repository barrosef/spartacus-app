function GraduationCard({
  group,
  modalityName,
  archived,
}: {
  group: GraduationBreakdown;
  modalityName: string;
  archived: boolean;
}) {
  const beltColor = group.belt ? getBeltColor(modalityName, group.belt) : NO_GRADUATION_COLOR;
  const widths = trackWidths(group.counts);
  return (
    <View style={[styles.gradCard, archived && styles.gradCardArchived]}>
      <View style={styles.gradHead}>
        <View style={styles.beltPill}>
          <View style={[styles.beltBar, { backgroundColor: beltColor }]} />
          {!!group.degree && (
            <View style={styles.pips}>
              {Array.from({ length: group.degree }).map((_, i) => (
                <View key={i} style={styles.pip} />
              ))}
            </View>
          )}
          <Text style={styles.beltText}>{graduationLabel(group)}</Text>
        </View>
        {group.pending && (
          <View style={styles.pendingTag}>
            <Text style={styles.pendingTagText}>EM ANÁLISE</Text>
          </View>
        )}
        {archived && <Text style={styles.archivedTag}>Faixa anterior</Text>}
      </View>
      <View style={styles.gradStats}>
        <GradStat value={group.counts.confirmed} label="Present." color={colors.success} />
        <GradStat value={group.counts.absent} label="Faltas" color={colors.error} />
        <GradStat value={group.counts.absentJustified} label="Justif." color={colors.primary} />
        <GradStat value={formatPercent(group.percent)} label="Freq." color={colors.foreground} />
      </View>
      <View style={styles.track}>
        {widths.ok > 0 && <View style={[styles.trackFill, { width: `${widths.ok}%`, backgroundColor: colors.success }]} />}
        {widths.rev > 0 && <View style={[styles.trackFill, { width: `${widths.rev}%`, backgroundColor: colors.warning }]} />}
        {widths.miss > 0 && <View style={[styles.trackFill, { width: `${widths.miss}%`, backgroundColor: colors.error }]} />}
      </View>
    </View>
  );
}

function GradStat({ value, label, color }: { value: number | string; label: string; color: string }) {
  return (
    <View style={styles.gradStat}>
      <Text style={[styles.gradStatValue, { color }]}>{value}</Text>
      <Text style={styles.gradStatLabel}>{label}</Text>
    </View>
  );
}

function RecordRow({
  record,
  canJustify,
  prazoExpired = false,
  onJustify,
}: {
  record: AttendanceRecord;
  canJustify: boolean;
  prazoExpired?: boolean;
  onJustify: () => void;
}) {
  const meta = STATUS_META[record.status] ?? STATUS_META.absent;
  return (
    <View style={styles.recordRow}>
      <View style={styles.recordInfo}>
        <Text style={styles.recordDate}>{record.date}</Text>
        <Text style={styles.recordSub}>
          {record.modalityName}
          {record.teacherName ? ` · ${record.teacherName}` : ""}
        </Text>
        {record.justification && (
          <Text style={styles.justification}>{record.justification}</Text>
        )}
      </View>
      <View style={styles.recordActions}>
        <View style={[styles.badge, { backgroundColor: meta.bg }]}>
          <Feather name={meta.icon} size={11} color={meta.text} />
          <Text style={[styles.badgeText, { color: meta.text }]}>{record.statusLabel}</Text>
        </View>
        {canJustify && (
          <TouchableOpacity style={styles.justifyBtn} onPress={onJustify} activeOpacity={0.8}>
            <Feather name="edit-3" size={11} color={colors.primary} />
            <Text style={styles.justifyBtnText}>Justificar</Text>
          </TouchableOpacity>
        )}
        {!canJustify && prazoExpired && (
          <Text style={styles.prazoExpired}>Prazo para justificar encerrado</Text>
        )}
      </View>
    </View>
  );
}

