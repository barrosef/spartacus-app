/** Days after the aula's date during which "Justificar" is offered — must
 * mirror the backend's `_JUSTIFY_PRAZO_DAYS` (app/routers/attendance.py).
 * This is a display-only heuristic (based on `dateSort`, a date without
 * time-of-day); the server is authoritative and re-validates on submit. */
const JUSTIFY_PRAZO_DAYS = 7;

function withinJustifyPrazo(dateSort: string): boolean {
  const parts = dateSort.split("-").map(Number);
  if (parts.length !== 3 || parts.some((n) => Number.isNaN(n))) return false;
  const [y, m, d] = parts;
  const deadline = new Date(y, m - 1, d);
  deadline.setDate(deadline.getDate() + JUSTIFY_PRAZO_DAYS + 1); // exclusive end-of-day
  return new Date() < deadline;
}

/** Synthetic placeholder ids (`absent_{dateSort}`) are generated by the
 * backend's `_build_month_records` (app/services/attendance_service.py) for
 * scheduled class days with no real Firestore attendance doc. There is
 * nothing to justify for these — only real absence docs (id = Firestore
 * doc id) are justifiable. */
function isRealRecordId(id: string): boolean {
  return !id.startsWith("absent_");
}

